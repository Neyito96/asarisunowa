#!/usr/bin/env node
// public/library の純粋モジュールを、依存順にGAS用の1ファイル(各モジュールをIIFEで名前空間化)へ束ねる。生成物は COPY専用(本番GASフォルダには置かない)。
// 使い方: node scripts/build-copy-gas.mjs  → scripts/copy-gas-proposal/P26Bundle.gs
import fs from 'node:fs';import path from 'node:path';
const LIB=new URL('../public/library/',import.meta.url).pathname,OUT=new URL('./copy-gas-proposal/P26Bundle.gs',import.meta.url).pathname;
const ENTRY=['daily-pipeline','playlist-engine','playlist-router'];
const order=[],seen=new Set();
const imports=src=>[...src.matchAll(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.mjs';?\s*$/gm)];
function visit(n){if(seen.has(n))return;seen.add(n);for(const m of imports(fs.readFileSync(LIB+n+'.mjs','utf8')))visit(m[2]);order.push(n);}
ENTRY.forEach(visit);
const ns=n=>'M_'+n.replace(/-/g,'_');
let out=`// GENERATED by scripts/build-copy-gas.mjs — 編集禁止。COPY GAS専用。本番GAS/本番Spreadsheetへは配置しない。\n// 元: ${order.map(n=>'public/library/'+n+'.mjs').join(', ')}\n`;
for(const n of order){
  let src=fs.readFileSync(LIB+n+'.mjs','utf8');const pre=[],ex=[];
  src=src.replace(/^import\s*\{([^}]*)\}\s*from\s*'\.\/([\w-]+)\.mjs';?\s*$/gm,(_,names,mod)=>{pre.push(`const {${names.trim()}} = ${ns(mod)};`);return '';});
  src=src.replace(/^export\s*\{\s*([\w$]+)\s+as\s+([\w$]+)\s*\};?\s*$/gm,(_,a,b)=>{ex.push(`${b}: ${a}`);return '';});
  src=src.replace(/^export\s+(?:async\s+)?(?:const|let|function\*?|class)\s+([\w$]+)/gm,(m,name)=>{ex.push(`${name}: ${name}`);return m.replace(/^export\s+/,'');});
  out+=`\nconst ${ns(n)} = (function () {\n${pre.join('\n')}\n${src}\nreturn {${ex.join(', ')}};\n})();\n`;
}
fs.writeFileSync(OUT,out);console.log('wrote',OUT,out.length,'bytes; modules:',order.join(','));
