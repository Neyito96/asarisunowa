// Build the GAS-compatible parser from existing V3 / Phase 11 mechanical parsing.
import fs from 'node:fs';
let clean=fs.readFileSync('public/library/library-clean.mjs','utf8').replace(/export \{[^}]+\};/,'');
let editor=fs.readFileSync('public/library/description-editor.mjs','utf8').replace(/^import .*\n/m,'').replaceAll('export ','');
const start=editor.indexOf('function publicationUrl('),end=editor.indexOf('function descriptionLines(');
editor=editor.slice(0,start)+`function publicationUrl(raw) {
 const m=String(raw).match(/^(https?:)\\/\\/([^/?#]+)([^?#]*)(?:\\?([^#]*))?(#.*)?$/);
 if(!m||!/^[-a-z0-9.]+(?::\\d+)?$/i.test(m[2]))return '';
 const query=(m[4]||'').split('&').filter(x=>x&&!/^(utm_[^=]*|iref|ref|fbclid|gclid|si)=/i.test(x)).join('&');
 return m[1]+'//'+m[2].toLowerCase()+(m[3]||'/')+(query?'?'+query:'')+(m[5]||'');
}
`+editor.slice(end);
// The existing parser omits the common 【出演】 heading. Keep this fix isolated in the port.
editor=editor.replace('^【出演[・／/]スタッフ】|^【出演者】|^【スタッフ】','^【出演[・／/]スタッフ】|^【出演】|^【出演者】|^【スタッフ】');
editor=editor.replace("else if(/^(?:【お知らせ】", "else if(/^(?:【おねがい】|【朝ポキ情報】|【お知らせ】");
fs.writeFileSync('scripts/google-apps-script/LibraryOfficialParser.gs',`// Generated by scripts/phase14/build-parser.mjs. Namespace isolates existing GAS globals.\nvar LibraryOfficialParser = (function(){\n${clean}\nconst cleanDescription=libV3Clean_;\n${editor}\nreturn {parse:editDescription,clean:cleanDescription,url:publicationUrl};\n})();\n`);
