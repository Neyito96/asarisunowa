import fs from 'node:fs';
const source=fs.readFileSync(new URL('../lib/podcast-platform-evidence.mjs',import.meta.url),'utf8');
const names=[...source.matchAll(/export (?:function|const) (\w+)/g)].map(x=>x[1]);
const generated='// GENERATED by scripts/generate-platform-evidence.mjs; edit lib/podcast-platform-evidence.mjs.\nvar PodcastPlatformEvidence = (function(){\n'+source.replace(/export /g,'')+'\nreturn {'+names.join(',')+'};\n}());\n';
const target=new URL('./google-apps-script/PlatformEvidence.js',import.meta.url);
if(process.argv.includes('--check')){if(fs.readFileSync(target,'utf8')!==generated)throw Error('Generated GAS is stale');}else fs.writeFileSync(target,generated);
